import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ledgerPath = path.join(root, "docs", "seo", "SEO-MIGRATION-PHASES-AND-URL-LEDGER.md");
const htaccessPath = path.join(root, "public", ".htaccess");
const exportPath = path.join(root, "out");
const reportPath = path.join(root, "docs", "seo", "PHASE-4-HOSTINGER-REDIRECT-AUDIT.csv");
const canonicalOrigin = "https://www.cleanworxnj.com";
const beginMarker = "# BEGIN SEO migration ledger (generated by scripts/seo-migration.mjs)";
const endMarker = "# END SEO migration ledger";

function readLedger() {
  const rows = fs.readFileSync(ledgerPath, "utf8").split(/\r?\n/)
    .filter((line) => /^\|\s*\d+\s*\|/.test(line))
    .map((line) => {
      const cells = line.slice(1, -1).split("|").map((cell) => cell.trim().replace(/^`|`$/g, ""));
      assert.equal(cells.length, 7, `Malformed ledger row: ${line}`);
      const source = new URL(cells[1]);
      const destination = new URL(cells[5], canonicalOrigin);
      assert.equal(cells[4], "301", `Unexpected action for ${source.href}`);
      assert.equal(source.hostname.replace(/^www\./, ""), "cleanworxnj.com");
      assert.equal(destination.origin, canonicalOrigin);
      assert.equal(source.search, "", `Source query must be handled generically: ${source.href}`);
      return { source: source.href, sourcePath: source.pathname, destination: destination.href };
    });

  assert.equal(rows.length, 143, "The ledger must contain exactly 143 redirect rows");
  assert.equal(new Set(rows.map((row) => row.source)).size, 143, "Duplicate source URL in ledger");
  const paths = rows.filter((row) => row.sourcePath !== "/");
  assert.equal(paths.length, 141, "Expected 141 old paths plus two home variants");
  assert.equal(new Set(paths.map((row) => row.sourcePath)).size, 138,
    "Expected three old paths shared by www and non-www URLs");
  for (const row of paths) {
    assert.ok(paths.filter((other) => other.sourcePath === row.sourcePath)
      .every((other) => other.destination === row.destination),
    `Conflicting destinations for ${row.sourcePath}`);
  }
  assert.equal(rows.filter((row) => row.sourcePath === "/").length, 2);
  assert.ok(!paths.some((row) => rows.some((other) => new URL(other.destination).pathname === row.sourcePath)),
    "A destination is another old path, creating a chain");
  return rows;
}

function uniquePathRows(rows) {
  return [...new Map(rows.filter((row) => row.sourcePath !== "/")
    .map((row) => [row.sourcePath, row])).values()];
}

function ruleFor(row) {
  const slug = row.sourcePath.slice(1);
  assert.match(slug, /^[a-z0-9-]+$/, `Unsafe or unexpected source path: ${row.sourcePath}`);
  return `RewriteRule ^${slug}/?$ ${row.destination} [R=301,L,NE]`;
}

function generate(rows) {
  const rules = uniquePathRows(rows).map(ruleFor);
  const content = [
    "Options -MultiViews",
    "RewriteEngine On",
    "",
    beginMarker,
    ...rules,
    endMarker,
    "",
    "# Keep utility redirects after the ledger so old URLs always reach their final destination.",
    `RewriteRule ^addons/?$ ${canonicalOrigin}/add-ons [R=301,L,NE]`,
    "RewriteRule ^booking/?$ https://cleanworx-llc.square.site/ [R=302,L,NE]",
    `RewriteRule ^sitemap/?$ ${canonicalOrigin}/sitemap.xml [R=301,L,NE]`,
    "",
    "# Canonicalize remaining routes, including the two legacy home variants, in one hop.",
    "RewriteCond %{HTTP_HOST} !^www\\.cleanworxnj\\.com$ [NC,OR]",
    "RewriteCond %{HTTPS} !=on",
    `RewriteRule ^(.*)$ ${canonicalOrigin}/$1 [R=301,L,NE]`,
    "",
    "# Next.js exports /about as about.html; keep extensionless URLs working.",
    "RewriteRule ^(.+)/$ /$1 [R=301,L]",
    "RewriteCond %{REQUEST_FILENAME} !-f",
    "RewriteCond %{REQUEST_FILENAME} !-d",
    "RewriteCond %{REQUEST_FILENAME}.html -f",
    "RewriteRule ^(.+)$ $1.html [L]",
    "",
    "ErrorDocument 404 /404.html",
    "",
  ].join("\n");
  fs.writeFileSync(htaccessPath, content);
  console.log(`Generated ${rules.length} path rules plus canonical redirects for two home variants.`);
}

function verifyRules(content, rows) {
  const begin = content.indexOf(beginMarker);
  const end = content.indexOf(endMarker);
  assert.ok(begin >= 0 && end > begin, "Migration rule block is missing");
  const rules = content.slice(begin + beginMarker.length, end).split(/\r?\n/).filter(Boolean);
  const expected = uniquePathRows(rows).map(ruleFor);
  assert.deepEqual(rules, expected, "Migration rules differ from ledger or have duplicate/missing entries");
  assert.ok(!content.includes("RewriteRule ^services/?$"), "/services must remain a page");
  assert.ok(content.indexOf("RewriteRule ^(.*)$") > end, "Host canonicalization must follow the ledger");
  assert.ok(content.includes("RewriteCond %{HTTP_HOST} !^www\\.cleanworxnj\\.com$ [NC,OR]"));
  assert.ok(content.includes("RewriteCond %{HTTPS} !=on"));
  assert.ok(content.includes(`RewriteRule ^(.*)$ ${canonicalOrigin}/$1 [R=301,L,NE]`));
  assert.ok(content.includes(`RewriteRule ^addons/?$ ${canonicalOrigin}/add-ons [R=301,L,NE]`));
  assert.ok(content.includes("RewriteRule ^booking/?$ https://cleanworx-llc.square.site/ [R=302,L,NE]"));
  assert.ok(content.includes(`RewriteRule ^sitemap/?$ ${canonicalOrigin}/sitemap.xml [R=301,L,NE]`));
  assert.ok(!content.includes("QSD"), "Query strings must pass through unchanged");
}

function exportFileFor(destination) {
  const pathname = new URL(destination).pathname;
  return path.join(exportPath, pathname === "/" ? "index.html" : `${pathname.slice(1)}.html`);
}

function exportedHtmlFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) return exportedHtmlFiles(filename);
    return entry.name.endsWith(".html") ? [filename] : [];
  });
}

function verifyExport(rows) {
  assert.ok(fs.existsSync(exportPath), "Run npm run build:hostinger first");
  const sourceRules = fs.readFileSync(htaccessPath, "utf8");
  const bundledRules = fs.readFileSync(path.join(exportPath, ".htaccess"), "utf8");
  assert.equal(bundledRules, sourceRules, "Exported .htaccess differs from public/.htaccess");
  verifyRules(bundledRules, rows);

  const sitemap = fs.readFileSync(path.join(exportPath, "sitemap.xml"), "utf8");
  const sitemapUrls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1]);
  assert.equal(new Set(sitemapUrls).size, sitemapUrls.length, "Duplicate URL in sitemap");
  assert.ok(!sitemapUrls.some((url) => url.endsWith("/services")), "/services must be excluded from sitemap");
  assert.ok(!sitemapUrls.some((url) => rows.some((row) => row.source === url)), "Legacy URL in sitemap");
  assert.ok(sitemapUrls.every((url) => url.startsWith(canonicalOrigin)), "Noncanonical sitemap URL");
  const servicesHtml = fs.readFileSync(path.join(exportPath, "services.html"), "utf8");
  assert.match(servicesHtml, /<meta[^>]+name="robots"[^>]+content="noindex, follow"/i,
    "/services needs noindex, follow in the exported HTML");

  for (const row of rows) {
    assert.ok(fs.existsSync(exportFileFor(row.destination)), `Destination missing from export: ${row.destination}`);
    assert.ok(sitemapUrls.includes(row.destination.replace(/\/$/, "")) ||
      (row.destination === `${canonicalOrigin}/` && sitemapUrls.includes(canonicalOrigin)),
    `Destination missing from sitemap: ${row.destination}`);
  }
  assert.ok(sitemapUrls.every((url) => fs.existsSync(exportFileFor(url))), "Sitemap lists a missing exported page");

  for (const destination of new Set(rows.map((row) => row.destination))) {
    const html = fs.readFileSync(exportFileFor(destination), "utf8");
    assert.doesNotMatch(html, /<meta[^>]+name="robots"[^>]+content="[^"]*noindex/i,
      `Destination is noindex: ${destination}`);
    const canonical = html.match(/<link[^>]+rel="canonical"[^>]+href="([^"]+)"/i)?.[1];
    assert.equal(canonical?.replace(/\/$/, ""), destination.replace(/\/$/, ""),
      `Destination has wrong canonical: ${destination}`);
  }

  const oldPaths = new Set(rows.map((row) => row.sourcePath).filter((pathname) => pathname !== "/"));
  for (const filename of exportedHtmlFiles(exportPath)) {
    const html = fs.readFileSync(filename, "utf8");
    for (const match of html.matchAll(/<a\s[^>]*href="([^"]+)"/gi)) {
      const href = match[1];
      if (!href.startsWith("/") && !href.startsWith(canonicalOrigin)) continue;
      const linked = new URL(href, canonicalOrigin);
      assert.ok(!oldPaths.has(linked.pathname),
        `Internal link to legacy URL in ${path.relative(exportPath, filename)}: ${href}`);
    }
  }
  return sitemapUrls.length;
}

function writeReport(rows) {
  const quote = (value) => `"${value.replaceAll('"', '""')}"`;
  const lines = ["source,action,destination,rule,exported_destination,verification"];
  for (const row of rows) {
    const rule = row.sourcePath === "/" ? "canonical host/protocol rule" : ruleFor(row);
    lines.push([row.source, "301", row.destination, rule, path.relative(root, exportFileFor(row.destination)),
      "PASS_STATIC"].map(quote).join(","));
  }
  fs.writeFileSync(reportPath, `${lines.join("\n")}\n`);
}

const rows = readLedger();
const command = process.argv[2];
if (command === "generate") {
  generate(rows);
} else if (command === "verify") {
  verifyRules(fs.readFileSync(htaccessPath, "utf8"), rows);
  const count = verifyExport(rows);
  writeReport(rows);
  console.log(`PASS: ${rows.length} ledger rows, 138 direct path rules, 2 home variants, ${count} sitemap URLs, all destinations exported.`);
  console.log(`Static audit: ${path.relative(root, reportPath)}. Live HTTP status checks remain for phase 5.`);
} else {
  console.error("Usage: node scripts/seo-migration.mjs generate|verify");
  process.exitCode = 1;
}
